-- Creates tables for MY CONCRETE bookings, site visits, quotes, and enquiries,
-- grants table/sequence INSERT permissions to anon & authenticated roles,
-- and enables Row Level Security (RLS) for safe form inserts via your publishable key.

create table if not exists public.bookings (
  id bigint generated by default as identity primary key,
  booking_code text not null unique,
  product_slug text not null,
  product_name text not null,
  grade text not null,
  quantity_m3 double precision not null,
  unit_type text not null default 'm3',
  usage_type text not null default '',
  slump_mm text not null default '',
  pump_type text not null default 'none',
  delivery_date text not null,
  slot_id text not null,
  slot_label text not null,
  site_address text not null,
  landmark text default '',
  city text not null,
  site_lat double precision not null default 0,
  site_lng double precision not null default 0,
  distance_km double precision not null default 0,
  estimated_concrete_amount double precision not null default 0,
  estimated_delivery_fee double precision not null default 0,
  estimated_pump_fee double precision not null default 0,
  estimated_total double precision not null default 0,
  customer_name text not null,
  phone text not null,
  email text default '',
  gst_number text default '',
  notes text default '',
  status text not null default 'confirmed',
  notify_email_status text not null default 'pending',
  notify_whatsapp_status text not null default 'pending',
  notified_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create index if not exists idx_supabase_bookings_date_slot
  on public.bookings (delivery_date, slot_id);
create index if not exists idx_supabase_bookings_phone
  on public.bookings (phone);

create table if not exists public.site_visits (
  id bigint generated by default as identity primary key,
  visit_code text not null unique,
  visit_type text not null,
  preferred_date text not null,
  preferred_time text not null,
  location text default '',
  customer_name text not null,
  phone text not null,
  email text default '',
  notes text default '',
  status text not null default 'scheduled',
  notify_email_status text not null default 'pending',
  notify_whatsapp_status text not null default 'pending',
  notified_at timestamptz,
  created_at timestamptz not null default now()
);

create table if not exists public.quotes (
  id bigint generated by default as identity primary key,
  quote_code text not null unique,
  project_type text not null,
  grade text not null,
  quantity_m3 double precision not null,
  location text not null,
  timeline text not null,
  customer_name text not null,
  phone text not null,
  email text default '',
  notes text default '',
  attachment_name text default '',
  status text not null default 'new',
  notify_email_status text not null default 'pending',
  notify_whatsapp_status text not null default 'pending',
  notified_at timestamptz,
  created_at timestamptz not null default now()
);

create table if not exists public.enquiries (
  id bigint generated by default as identity primary key,
  type text not null default 'contact',
  name text not null,
  phone text not null,
  email text default '',
  city text not null,
  company_or_role text default '',
  message text not null,
  consent boolean not null default true,
  status text not null default 'new',
  notify_email_status text not null default 'pending',
  notify_whatsapp_status text not null default 'pending',
  notified_at timestamptz,
  created_at timestamptz not null default now()
);

alter table public.bookings
  add column if not exists notify_email_status text not null default 'pending',
  add column if not exists notify_whatsapp_status text not null default 'pending',
  add column if not exists notified_at timestamptz;

alter table public.site_visits
  add column if not exists notify_email_status text not null default 'pending',
  add column if not exists notify_whatsapp_status text not null default 'pending',
  add column if not exists notified_at timestamptz;

alter table public.quotes
  add column if not exists notify_email_status text not null default 'pending',
  add column if not exists notify_whatsapp_status text not null default 'pending',
  add column if not exists notified_at timestamptz;

alter table public.enquiries
  add column if not exists notify_email_status text not null default 'pending',
  add column if not exists notify_whatsapp_status text not null default 'pending',
  add column if not exists notified_at timestamptz;

-- Required PostgreSQL table & sequence grants for Supabase publishable/anon key inserts
grant usage on schema public to anon, authenticated;
grant insert on table public.bookings to anon, authenticated;
grant insert on table public.site_visits to anon, authenticated;
grant insert on table public.quotes to anon, authenticated;
grant insert on table public.enquiries to anon, authenticated;
grant usage, select on all sequences in schema public to anon, authenticated;

alter table public.bookings enable row level security;
alter table public.site_visits enable row level security;
alter table public.quotes enable row level security;
alter table public.enquiries enable row level security;

-- Allow website form submissions using your publishable key (no public SELECT of customer PII)
drop policy if exists "Allow public booking inserts" on public.bookings;
create policy "Allow public booking inserts"
  on public.bookings for insert
  to anon, authenticated
  with check (true);

drop policy if exists "Allow public site visit inserts" on public.site_visits;
create policy "Allow public site visit inserts"
  on public.site_visits for insert
  to anon, authenticated
  with check (true);

drop policy if exists "Allow public quote inserts" on public.quotes;
create policy "Allow public quote inserts"
  on public.quotes for insert
  to anon, authenticated
  with check (true);

drop policy if exists "Allow public enquiry inserts" on public.enquiries;
create policy "Allow public enquiry inserts"
  on public.enquiries for insert
  to anon, authenticated
  with check (true);

